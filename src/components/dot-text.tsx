export function DotText({
  text,
  className = '',
  decorative = false,
  maxCharacters = 10,
}: Props) {
  const characters = [...text];
  // Long or unsupported values remain exact, readable ordinary text.
  if (
    text.length > maxCharacters ||
    characters.some((letter) => !glyphs[letter])
  ) {
    return (
      <span
        className={`dot-text-fallback ${className}`}
        aria-hidden={decorative || undefined}
      >
        {text}
      </span>
    );
  }
  return (
    <svg
      className={`dot-text ${className}`}
      viewBox={`0 0 ${Math.max(1, text.length * 36 - 6)} 42`}
      role={decorative ? undefined : 'img'}
      aria-label={decorative ? undefined : text}
      aria-hidden={decorative || undefined}
      focusable="false"
    >
      {characters.flatMap((letter, index) =>
        glyphs[letter]?.flatMap((row, y) =>
          [...row].flatMap((pixel, x) =>
            pixel === '1' ? (
              <circle
                key={`${index}-${y}-${x}`}
                cx={index * 36 + x * 6 + 3}
                cy={y * 6 + 3}
                r={1.95}
              />
            ) : (
              []
            ),
          ),
        ),
      )}
    </svg>
  );
}
